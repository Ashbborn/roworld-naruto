#!/usr/bin/env python3
"""The tailed beasts, the Akatsuki emblem and the Akatsuki members, hand-made as SVG (round 2,
2026-11-23): every drawing is anchor-point outlines (tools/naruto/beastkit.py), one geometry rendered
twice, as the white mask the game tints and as a full-colour, cel-shaded portrait.

  beasts      1..9   256 px masks (tinted in game): tools/naruto/beasts/<name>.py, its FINAL draft
  portraits   1..9   512 px colour portraits (ink outline, chakra glow) for the awakening/capture banners
  akatsuki           256 px cloud mask (the game tints it red): tools/naruto/akatsuki_cloud.py
  akatsuki_color     512 px the emblem in its colours (red, white border, curls)
  members            128 px bust masks (shadow figures with glowing eyes): tools/naruto/members/<name>.py
  members_color      256 px colour busts

RETIRED 11-23: the game's art is now generated from the official references and picked by the owner
(tools/naruto/ai_art.py; its `wire` command writes assets/beast_art/ and src/shared/Assets/BeastArt.luau).
This script renders into build/beast_art_svg/ so it cannot overwrite that art, and --upload (which would
replace BeastArt.luau with these drawings) is refused unless --replace-ai-art is given too.

Out: build/beast_art_svg/*.png and, with --upload --replace-ai-art (tools/upload.py -> Open Cloud on
Windows, content-hash cached), src/shared/Assets/BeastArt.luau. --sheet writes the review sheets
(tools/naruto/make_r2_sheets.py).

Usage: python tools/naruto/make_beast_art.py [--sheet] [--upload --replace-ai-art]
"""
import argparse
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import akatsuki_cloud  # noqa: E402
import beastkit as bk  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "build", "beast_art_svg")  # retired: the game's art is assets/beast_art (ai_art.py)
MANIFEST = os.path.join(ROOT, "src", "shared", "Assets", "BeastArt.luau")
BEAST_PX = 256
PORTRAIT_PX = 512
CLOUD_COLOR_PX = 512
MEMBER_PX = 128
MEMBER_COLOR_PX = 256
#: the cloud mask's style (akatsuki_cloud.cloud_mask): "rim" shows the white border as a gap
CLOUD_STYLE = "rim"

BEAST_NAMES = ["shukaku", "matatabi", "isobu", "son_goku", "kokuo", "saiken", "chomei", "gyuki", "kurama"]
MEMBERS = ["itachi", "kisame", "deidara", "sasori", "hidan", "kakuzu", "pain", "konan", "tobi", "zetsu"]


def load(path):
    spec = importlib.util.spec_from_file_location("art_" + os.path.splitext(os.path.basename(path))[0], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def beast_module(name):
    return load(os.path.join(HERE, "beasts", name + ".py"))


def member_module(name):
    return load(os.path.join(HERE, "members", name + ".py"))


def final_parts(mod, draft=None):
    return mod.DRAFTS[draft or getattr(mod, "FINAL", "A")]()


def render_beast(name, draft=None):
    """(mask 256, portrait 512) of a beast's FINAL (or given) draft."""
    mod = beast_module(name)
    parts = final_parts(mod, draft)
    return (bk.render_mask(parts, BEAST_PX),
            bk.render_colour(parts, mod.PALETTE, PORTRAIT_PX, glow=getattr(mod, "GLOW", None)))


def render_member(name, draft=None):
    mod = member_module(name)
    parts = final_parts(mod, draft)
    return (bk.render_mask(parts, MEMBER_PX),
            bk.render_colour(parts, mod.PALETTE, MEMBER_COLOR_PX, glow=getattr(mod, "GLOW", None), outline=0.014))


def render_all():
    """Every image: {key: (path, PIL)}."""
    os.makedirs(OUT, exist_ok=True)
    out = {}

    def put(key, fname, im):
        p = os.path.join(OUT, fname)
        im.save(p, optimize=True)
        out[key] = (p, im)

    for name in BEAST_NAMES:
        m, c = render_beast(name)
        put("beast_" + name, f"beast_{name}.png", m)
        put("portrait_" + name, f"portrait_{name}.png", c)
    put("akatsuki", "akatsuki.png", akatsuki_cloud.cloud_mask(BEAST_PX, CLOUD_STYLE))
    put("akatsuki_color", "akatsuki_color.png", akatsuki_cloud.cloud_colour(CLOUD_COLOR_PX))
    for name in MEMBERS:
        m, c = render_member(name)
        put("member_" + name, f"member_{name}.png", m)
        put("member_color_" + name, f"member_color_{name}.png", c)
    return out


def write_manifest(ids):
    L = [
        "-- GENERATED by tools/naruto/make_beast_art.py — do not edit by hand.",
        "-- Hand-made SVG art (tools/naruto/beastkit.py). Masks are white: tint them with ImageColor3;",
        "-- the *_color / portraits images are full colour: do not tint them.",
        "return {",
        f"\t--- the nine tailed beasts, index = tail count, {BEAST_PX} px white masks: " + ", ".join(BEAST_NAMES),
        "\tbeasts = {",
    ]
    for i, n in enumerate(BEAST_NAMES, 1):
        L.append(f'\t\t"{ids["beast_" + n]}", -- {i} {n}')
    L += [
        "\t},",
        f"\t--- the same beasts as full-colour portraits, {PORTRAIT_PX} px (ink outline, chakra glow round",
        "\t--- them, transparent): the awakening / capture banners",
        "\tportraits = {",
    ]
    for i, n in enumerate(BEAST_NAMES, 1):
        L.append(f'\t\t"{ids["portrait_" + n]}", -- {i} {n}')
    L += [
        "\t},",
        f"\t--- the Akatsuki cloud emblem, {BEAST_PX} px white mask (the game tints it red)",
        f'\takatsuki = "{ids["akatsuki"]}",',
        f"\t--- the emblem in its own colours (red, white border and curls), {CLOUD_COLOR_PX} px",
        f'\takatsuki_color = "{ids["akatsuki_color"]}",',
        f"\t--- the Akatsuki members' busts, {MEMBER_PX} px white masks (shadow figures, glowing eyes)",
        "\tmembers = {",
    ]
    for n in MEMBERS:
        L.append(f'\t\t{n} = "{ids["member_" + n]}",')
    L += ["\t},", f"\t--- the same busts in colour, {MEMBER_COLOR_PX} px", "\tmembers_color = {"]
    for n in MEMBERS:
        L.append(f'\t\t{n} = "{ids["member_color_" + n]}",')
    L += ["\t},", "}"]
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", action="store_true")
    ap.add_argument("--upload", action="store_true")
    ap.add_argument("--replace-ai-art", action="store_true",
                    help="with --upload: replace the picked AI art in BeastArt.luau with these drawings")
    args = ap.parse_args()
    if args.upload and not args.replace_ai_art:
        ap.error("BeastArt.luau holds the owner's picked AI art (tools/naruto/ai_art.py wire); "
                 "--upload would replace it: add --replace-ai-art if that is really wanted")
    out = render_all()
    print("wrote", len(out), "->", os.path.relpath(OUT, ROOT))
    if args.sheet:
        import make_r2_sheets
        for p in make_r2_sheets.build_all():
            print(p)
    if args.upload:
        sys.path.insert(0, os.path.join(ROOT, "tools"))
        import upload as up
        paths = [p for p, _ in out.values()]
        res = up.upload_images(paths)
        ids = {k: res[p] for k, (p, _) in out.items()}
        write_manifest(ids)
        print("manifest:", os.path.relpath(MANIFEST, ROOT))


if __name__ == "__main__":
    main()
